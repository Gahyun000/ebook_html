await page.waitForTimeout(80)
const beforeDup = await page.locator('.stage .fel').count()
await page.keyboard.press('Control+d')
await page.waitForTimeout(120)
check('단축키 복제(⌘/Ctrl+D)', (await page.locator('.stage .fel').count()) === beforeDup + 1)
await page.keyboard.press('Delete')
await page.waitForTimeout(120)
check('단축키 삭제(Delete)', (await page.locator('.stage .fel').count()) === beforeDup)
await page.keyboard.press('Control+z')
await page.waitForTimeout(120)
check('단축키 되돌리기(⌘/Ctrl+Z)', (await page.locator('.stage .fel').count()) === beforeDup + 1)
await page.keyboard.press('Control+Shift+z')
await page.waitForTimeout(120)
check('단축키 다시 실행(⌘/Ctrl+⇧+Z)', (await page.locator('.stage .fel').count()) === beforeDup)
// 방향키 이동
