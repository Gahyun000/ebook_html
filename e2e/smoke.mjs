await page.waitForTimeout(60)
check('도구 단축키(R=사각형)', (await page.locator('[data-tut="tool-box"].on').count()) === 1)
await page.keyboard.press('v')

await page.click('.manual-btn')
check('설명서 패널', (await page.locator('.manual-panel .mrow').count()) > 5)
await page.click('.manual-panel .close')

await page.locator('.help-btn', { hasText: '도움말' }).click()
await page.click('.help-tut-btn')
check('튜토리얼 코치 표시', await page.locator('.coach').isVisible())
check('튜토리얼 스포트라이트 링', (await page.locator('.tut-ring').count()) >= 1)
