// ===== 2차 기능 (환경설정 · 챗 · 토글 · 예시영상 · 액션) =====
await page.locator('.help-btn', { hasText: '환경설정' }).click()
await page.waitForSelector('.settings-card', { timeout: 4000 })
check('환경설정 모달 열림', await page.locator('.settings-card').isVisible())
check('환경설정 provider 로딩', (await page.locator('.settings-grid select').first().inputValue()) === 'self')
await page.locator('.settings-modal .close').click()
await page.waitForTimeout(200)

await page.locator('.chat-fab').click()
await page.waitForSelector('.chat-panel.open', { timeout: 4000 })
await page.locator('.chat-panel footer input').fill('안녕')
await page.locator('.chat-panel footer input').press('Enter')
await page.waitForTimeout(1200)
check('챗 대화 응답(스트리밍)', (await page.locator('.chat-bubble.assistant').count()) >= 2)
const preAct = await page.locator('.fitem').count()
await page.locator('.chat-panel footer input').fill('성과 카드 넣어줘')
await page.locator('.chat-panel footer input').press('Enter')
await page.waitForTimeout(1300)
check('챗 액션 브리지(카드 추가)', (await page.locator('.fitem').count()) === preAct + 1)
await page.locator('.chat-header-actions button').last().click()
await page.waitForTimeout(200)

await page.locator('.chip', { hasText: '빈 페이지' }).click()
await page.waitForSelector('.block-editor', { timeout: 4000 })
check('블록·토글 에디터', await page.locator('.block-editor').isVisible())
check('블록 미리보기 렌더', (await page.locator('.stage').innerText()).includes('새 페이지 제목'))
// 슬래시 메뉴로 토글 생성
await page.locator('.be-addblock').click()
await page.waitForTimeout(120)
const nta = page.locator('.be-ta').last()
