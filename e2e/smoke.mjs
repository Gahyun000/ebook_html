await page.locator('.seg button', { hasText: '세로 이북' }).click()

await page.click('[data-tut="tool-box"]')
await page.locator('.stage .freelayer').click({ position: { x: 120, y: 120 } })
await page.waitForTimeout(150)
check('자유 캔버스 도형 추가', (await page.locator('.stage .fel').count()) >= 1)
await page.click('[data-tut="tool-box"]')
await page.locator('.stage .freelayer').click({ position: { x: 300, y: 320 } })
await page.waitForTimeout(150)
