await page.waitForTimeout(150)
check('펜 자유선', (await page.locator('.stage .freeconn path[stroke-linecap="round"]').count()) >= 1)

// 타이포그래피 전환
await page.locator('.ty select').nth(0).selectOption({ label: '명조' })
await page.waitForTimeout(120)
check('폰트 전환 반영', (await page.locator('.pv-cap').innerText()).includes('커스텀 폰트'))
await page.locator('.ty select').nth(1).selectOption({ label: '크게' })
await page.waitForTimeout(120)
check('글자 크기 전환 반영', (await page.locator('.pv-cap').innerText()).includes('크게'))
// 문구 다듬기
await page.locator('.fld input').first().fill('  많은   공백   ')
await page.click('.polish-btn')
await page.waitForTimeout(120)
check('문구 다듬기(공백 정리)', (await page.locator('.fld input').first().inputValue()) === '많은 공백')
// 이미지 요소 추가
await page.click('[data-tut="tool-image"]')
await page.locator('.stage .freelayer').click({ position: { x: 210, y: 360 } })
await page.waitForTimeout(120)
check('이미지 요소 추가', (await page.locator('.stage .fel.image').count()) >= 1)
await page.click('[data-tut="tool-select"]')

// --- 키보드 단축키 ---
